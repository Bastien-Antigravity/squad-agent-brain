    _toolbox_dir = pathPath(_core_root_env).expanduser().resolve() / "microservice-toolbox" / "python"
    if _toolbox_dir.is_dir() and str(_toolbox_dir) not in sysPath:
        sysPath.insert(0, str(_toolbox_dir))
